<h2>¿Cómo se dividen los gastos en Carpoolear?</h2>

<h3>Sin lucro</h3>
<p>El principal concepto de Carpoolear es que es una plataforma colaborativa para compartir viajes sin fines de lucro. ¿Qué quiere decir esto? Que quien pone el auto es uno más en el viaje y no puede obtener un rédito económico por compartir el viaje. Por ello debe incluirse a sí mismo en la división de gastos, que sólo incluyen nafta, peajes y 1 litro para Carpoolear. No se puede incluir desgaste del auto ni ninguna otra cosa.</p>

<h3>Seguro automotor</h3>
<p>El hecho de que no se obtenga un lucro con el viaje es muy importante, además de porque es la idea detrás de Carpoolear, porque el seguro común para autos en Argentina no incluye el transporte de pasajeros, y sólo va a ofrecer cobertura si sólo hubo división de gastos.</p>

<h3>Cálculo</h3>
<p>Para el cálculo de la colaboración por persona tenemos en cuenta el precio de 1 L de nafta premium, la distancia, el consumo promedio de un auto en Argentina (8 L/100 km), un 15% extra para peajes, y 1L de nafta para Carpoolear. Eso es para un consumo promedio, y cada uno debe ajustarlo de acuerdo al consumo de su propio auto, con un tope máximo equivalente a 10 L/100 km (+25% sobre combustible y peajes). Todo esto se divide entre 4 o 5 personas, dependiendo si en el asiento de atrás hay dos o tres asientos disponibles.</p>

<p>Por ejemplo para un viaje típico de Rosario a Buenos Aires tenemos:</p>

<ul>
  <li>Distancia: 291 km</li>
  <li>Consumo promedio: 8 L/100 km</li>
  <li>Precio de 1 L de nafta premium (de referencia): $2.430</li>
</ul>

<p>Consumo: 23,28 L para hacer 291 km<br>
Subtotal combustible: 23,28 × 2.430 = $56.570,40<br>
Subtotal + peajes (15% extra): $56.570,40 × 1,15 = $65.055,96<br>
+ 1 L para Carpoolear: $2.430,00<br>
Colaboración total recomendada: $67.485,96</p>

<p><strong>Contribución por persona:</strong></p>
<ul>
  <li>$13.497,19 si son 5 personas</li>
  <li>$16.871,49 si son 4 personas</li>
</ul>

<p>Consumo máximo (equivalente a 10 L/100 km): 29,1 L para hacer 291 km<br>
Subtotal combustible: 29,1 × 2.430 = $70.713,00<br>
Subtotal + peajes (15% extra): $70.713,00 × 1,15 = $81.319,95<br>
+ 1 L para Carpoolear: $2.430,00<br>
Colaboración total máxima: $83.749,95</p>

<p><strong>Contribución por persona máxima:</strong></p>
<ul>
  <li>$16.749,99 si son 5 personas</li>
  <li>$20.937,49 si son 4 personas</li>
</ul>
